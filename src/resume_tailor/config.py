class _ConfigModule(ModuleType):
    """Route legacy test monkeypatches through the process default context."""

    def __setattr__(self, name: str, value: Any) -> None:
        global _DEFAULT
        if name in _PATH_NAMES:
            _DEFAULT = replace(_DEFAULT, paths={**_DEFAULT.paths, name: value})
        elif name in _CALIBRATION_NAMES:
            values = list(_DEFAULT.calibration)
            values[_CALIBRATION_NAMES.index(name)] = value
            _DEFAULT = replace(_DEFAULT, calibration=tuple(values))
        elif name == "_ACTIVE_WORKSPACE_ID":
            _DEFAULT = replace(_DEFAULT, workspace_id=value)
        elif name == "TAG_ALIASES":
            _DEFAULT = replace(_DEFAULT, tag_aliases=value)
        elif name == "VERB_FAMILIES":
            _DEFAULT = replace(_DEFAULT, verb_families=value)
        else:
            super().__setattr__(name, value)


sys.modules[__name__].__class__ = _ConfigModule
