def _dir_from_env(var: str, default: Path) -> Path:
    """Resolve a directory that a deployment may relocate, defaulting to the repo layout.

    Exists for the container, where `data/`, `templates/` and `output/` are bind mounts
    that need not sit under the package root. Reading these from the environment keeps
    the same code working from a source checkout and from `/app` inside an image.
    """
    raw = os.environ.get(var)
    return Path(raw).expanduser().resolve() if raw else default


