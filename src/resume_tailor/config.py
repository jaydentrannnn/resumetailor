MODEL = "claude-sonnet-5"

#: Generous ceiling — these are non-streaming calls whose real output is a few KB of
#: JSON, so this exists to prevent truncation, not to bound cost.
#:
#: Reasoning tokens are drawn from this same budget, so it must clear EFFORT's appetite:
#: at 16k a "medium"-effort rewrite spent the whole allowance thinking and came back
#: `stop_reason='max_tokens'` with nothing parseable.
#:
#: This is the *requested* ceiling, not necessarily the one sent. Anthropic refuses a
#: non-streaming request above 21,333 outright, so `max_tokens_for()` clamps that path —
#: read it before assuming a Claude run actually gets this budget.
MAX_TOKENS = 32_000

#: Anthropic's hard limit for a non-streaming request: the SDK rejects anything where
#: `3600 * max_tokens / 128_000 > 600` with "Streaming is required...". It is a client-side
#: refusal, so an over-large value fails before a token is spent rather than degrading.
#: Lifting it means converting the call sites to streaming, not raising this number.
ANTHROPIC_NONSTREAMING_MAX_TOKENS = 21_333

#: Thinking depth. JD extraction and bullet rewriting are short, well-specified tasks;
#: "medium" is the cost/quality sweet spot and can be raised if rewrites come back bland.
#: Passed as `output_config={"effort": ...}` by both API calls — see MAX_TOKENS above.
#:
#: This is now only the *fallback* default; per-stage effort is resolved through
#: `effort_for()` below, because effort is where most of the bill actually goes.
EFFORT = "medium"


# --------------------------------------------------------------------------------------
# LLM backends
# --------------------------------------------------------------------------------------
#
# Measured: the prompts here are tiny (the largest call sends ~2,800 input tokens and
# returns ~1,250), so at Sonnet rates a run should cost ~$0.03 per call. It bills ~$0.16.
# The difference is reasoning tokens, drawn from MAX_TOKENS and billed as output. Roughly
# 80% of the cost is thinking depth, not the model — which is why EFFORT is a per-stage
# knob below and not a single constant.
#
# `--model` then addresses the other 20% by routing stages at different backends entirely.

#: The three stages that call a model. Each resolves independently, so the cheap, safe
#: calls (extract, score) can run on a free backend while rewriting — where the
#: fabrication guard lives and where model quality actually shows — stays on Claude.
PURPOSES = ("extract", "score", "rewrite")

#: Providers `parse_spec` recognises as a leading segment. Anything else is read as a bare
#: model name, which matters more than it looks: `minimax-m3:cloud` contains a colon, so a
#: naive split would take "minimax-m3" for a provider.
PROVIDERS = ("anthropic", "openai", "ollama")

OLLAMA_BASE_URL = os.environ.get("OLLAMA_BASE_URL", "http://localhost:11434/v1")

#: Ollama Cloud runs this on Ollama's servers, so laptop VRAM is irrelevant. Note the
#: colon in the tag — see `parse_spec`.
OLLAMA_MODEL = os.environ.get("OLLAMA_MODEL", "minimax-m3:cloud")

#: Generous: a reasoning model over a cloud round trip is slow, and the score table sends
#: all 39 bullets at once.
LLM_TIMEOUT = float(os.environ.get("LLM_TIMEOUT", "300"))

#: How to ask for JSON on the OpenAI-compatible path.
#:
#: "prompt"  — schema in the system prompt + `response_format: json_object`.
#: "schema"  — additionally send `response_format: json_schema` with a strict schema.
#:
#: Defaults to "prompt" because it is what was *measured* to work. Ollama Cloud accepts
#: `json_schema` and silently ignores it, returning HTTP 200 with markdown prose; its own
#: native `format` parameter is equally unenforced for cloud models. Sending the schema is
#: therefore a round trip that always fails, and quota is finite. Set "schema" for
#: endpoints that genuinely constrain decoding (OpenAI, most vLLM deployments).
LLM_STRUCTURED_MODE = os.environ.get("LLM_STRUCTURED_MODE", "prompt")

#: Per-stage reasoning depth. Extraction is structured matching against a supplied
#: vocabulary and scoring is 39 independent judgements — neither is reasoning-hard, and
#: both were paying for "medium". Rewriting keeps it: that is the call where thinking
#: shows up in the output.
DEFAULT_EFFORT: dict[str, str] = {
    "extract": os.environ.get("LLM_EFFORT_EXTRACT", "low"),
    "score": os.environ.get("LLM_EFFORT_SCORE", "low"),
    "rewrite": os.environ.get("LLM_EFFORT_REWRITE", "medium"),
}

_ANTHROPIC_DEFAULT = f"anthropic:{MODEL}"
_OLLAMA_DEFAULT = f"ollama:{OLLAMA_MODEL}"

#: Named shorthands for `--model`. `hybrid` is the one worth understanding: the two cheap,
#: low-risk calls move to the free backend while rewriting stays on Claude, which is where
#: an invented tool or a restated number would actually cost you.
MODEL_PROFILES: dict[str, dict[str, str]] = {
    "claude": dict.fromkeys(PURPOSES, _ANTHROPIC_DEFAULT),
    "ollama": dict.fromkeys(PURPOSES, _OLLAMA_DEFAULT),
    "hybrid": {
        "extract": _OLLAMA_DEFAULT,
        "score": _OLLAMA_DEFAULT,
        "rewrite": _ANTHROPIC_DEFAULT,
    },
}


class Backend(NamedTuple):
    """A fully resolved routing decision for one stage."""

    provider: str
    model: str
    base_url: str | None
    effort: str

    def label(self) -> str:
        """Human-readable identity, for the run report."""
        return f"{self.provider}:{self.model}"


def parse_spec(spec: str) -> tuple[str, str, str | None]:
    """Parse `provider:model[@base_url]` into its parts.

    **Split on the first colon only.** Ollama tags embed colons, so the default model
    `ollama:minimax-m3:cloud` must yield model `minimax-m3:cloud`; splitting anywhere else
    breaks the primary use case rather than an edge case.

    A leading segment that is not a known provider means the whole string is a model name
    (`minimax-m3:cloud` on its own, or `claude-sonnet-5`). The provider is then inferred:
    Anthropic for `claude-*`, Ollama otherwise, since those are the two ways a bare name is
    realistically supplied.
    """
    spec = spec.strip()
    if not spec:
        raise ValueError("Empty model spec.")

    base_url: str | None = None
    if "@" in spec:
        spec, _, base_url = spec.partition("@")
        base_url = base_url or None

    head, sep, tail = spec.partition(":")
    if sep and head.lower() in PROVIDERS:
        provider, model = head.lower(), tail
    else:
        model = spec
        provider = "anthropic" if model.lower().startswith("claude") else "ollama"

    if not model:
        raise ValueError(f"Model spec {spec!r} names a provider but no model.")
    return provider, model, base_url


def _backend(spec: str, purpose: str, effort: str | None) -> Backend:
    provider, model, base_url = parse_spec(spec)
    if provider == "ollama":
        provider, base_url = "openai", base_url or OLLAMA_BASE_URL
    return Backend(
        provider=provider,
        model=model,
        base_url=base_url,
        effort=effort or DEFAULT_EFFORT.get(purpose, EFFORT),
    )


#: Resolved once per run by `resolve()`. Module state rather than a threaded parameter
#: because it is a process-wide run setting, like OUTPUT_DIR — and threading it would mean
#: touching every function between the CLI and the two API call sites.
_ACTIVE: dict[str, Backend] = {}


def resolve(
    profile: str | None = None,
    *,
    overrides: dict[str, str] | None = None,
    effort: str | None = None,
) -> dict[str, Backend]:
    """Decide which backend serves each stage, for the whole run.

    `profile` is a name from `MODEL_PROFILES` or a raw spec applied to every stage.
    `overrides` routes individual stages (`{"rewrite": "claude-sonnet-5"}`).

    Called once, early, so a bad spec fails before any file is read or any token spent.
    """
    profile = (profile or "claude").strip()

    if profile in MODEL_PROFILES:
        specs = dict(MODEL_PROFILES[profile])
    elif ":" in profile or "@" in profile or profile.lower().startswith("claude"):
        specs = dict.fromkeys(PURPOSES, profile)
    else:
        raise ValueError(
            f"Unknown model profile {profile!r}. Use one of "
            f"{', '.join(sorted(MODEL_PROFILES))}, or a spec like "
            f"'ollama:{OLLAMA_MODEL}'."
        )

    for purpose, spec in (overrides or {}).items():
        if purpose not in PURPOSES:
            raise ValueError(f"Unknown stage {purpose!r}. Expected one of {PURPOSES}.")
        specs[purpose] = spec

    _ACTIVE.clear()
    _ACTIVE.update(
        {p: _backend(specs[p], p, effort) for p in PURPOSES}
    )
    return dict(_ACTIVE)


def backend_for(purpose: str) -> Backend:
    """The resolved backend for one stage, defaulting to Claude if `resolve` never ran.

    The default matters: `jd.extract` and `rewrite.score_table` are importable library
    functions, and tests and scripts call them without going through the CLI.
    """
    if purpose not in PURPOSES:
        raise ValueError(f"Unknown stage {purpose!r}. Expected one of {PURPOSES}.")
    if not _ACTIVE:
        resolve("claude")
    return _ACTIVE[purpose]


def provider_for(purpose: str) -> str:
    return backend_for(purpose).provider


def model_for(purpose: str) -> str:
    return backend_for(purpose).model


def base_url_for(purpose: str) -> str | None:
    return backend_for(purpose).base_url


def effort_for(purpose: str) -> str:
    return backend_for(purpose).effort


def max_tokens_for(purpose: str) -> int:
    """Output ceiling for a stage, clamped to what its provider will actually accept.

    MAX_TOKENS is shared, but the providers are not interchangeable here: Anthropic
    refuses a non-streaming request above ANTHROPIC_NONSTREAMING_MAX_TOKENS before it
    leaves the client, while OpenAI-compatible endpoints have no such rule. Clamping per
    stage keeps a raised MAX_TOKENS from breaking `--model claude` on its first call,
    and keeps `--model hybrid` honest — the same run can send different ceilings to its
    two backends.
    """
    if backend_for(purpose).provider == "anthropic":
        return min(MAX_TOKENS, ANTHROPIC_NONSTREAMING_MAX_TOKENS)
    return MAX_TOKENS


def api_key_for(purpose: str) -> str:
    """Credential for a stage's provider.

    Local and Ollama Cloud endpoints authenticate through the daemon rather than a bearer
    token, so an empty string is a valid answer — `llm.py` omits the header entirely when
    there is no key, which some servers require.
    """
    backend = backend_for(purpose)
    if backend.provider == "anthropic":
        return anthropic_api_key()
    return os.environ.get("LLM_API_KEY", "") or os.environ.get("OLLAMA_API_KEY", "")


def fingerprint(purpose: str) -> str:
    """Identity of the backend serving a stage, for cache keys.

    Folded into `jd._slug` and `rewrite._score_cache_path`. Without it, switching models
    and re-running silently serves the *previous* model's output — the same class of bug
    `_PROMPT_VERSION` exists to prevent, and one that would make any A/B between backends
    meaningless.
    """
    backend = backend_for(purpose)
    return f"{backend.provider}|{backend.model}|{backend.effort}"


# --------------------------------------------------------------------------------------
# PDF rendering backend
# --------------------------------------------------------------------------------------
#
# The fit loop decides overflow on a real page count, which means something has to turn a
# .docx into a PDF. Word via COM does it best and runs only on Windows; LibreOffice
# headless does it anywhere, which is what makes the container possible.
#
# These are not interchangeable to the character: two engines lay text out slightly
# differently, so each carries its own calibration (see below). Switching backend without
# switching constants is the failure this pairing exists to prevent.

PDF_BACKENDS = ("word", "soffice")


def _default_pdf_backend() -> str:
    """Pick a converter for this machine: Word on Windows, LibreOffice elsewhere.

    Overridable with RESUME_TAILOR_PDF_BACKEND, which is how a Windows developer can test
    the container's engine without a container.
    """
    requested = os.environ.get("RESUME_TAILOR_PDF_BACKEND", "auto").strip().lower()
    if requested in PDF_BACKENDS:
        return requested
    if requested not in ("auto", ""):
        raise ValueError(
            f"RESUME_TAILOR_PDF_BACKEND must be one of {PDF_BACKENDS} or 'auto', "
            f"got {requested!r}"
        )
    return "word" if platform.system() == "Windows" else "soffice"


PDF_BACKEND = _default_pdf_backend()

#: How to invoke LibreOffice. The binary is `soffice` on Debian/Ubuntu and macOS; the
#: env var covers installations that are not on PATH.
SOFFICE_BINARY = os.environ.get("SOFFICE_BINARY") or shutil.which("soffice") or "soffice"

#: Seconds allowed for one LibreOffice conversion. A cold start costs a couple of seconds;
#: this only exists so a wedged process fails the run instead of hanging it forever.
SOFFICE_TIMEOUT = float(os.environ.get("SOFFICE_TIMEOUT", "120"))


# --------------------------------------------------------------------------------------
# Page fitting
# --------------------------------------------------------------------------------------

DEFAULT_PAGE_TARGET = 1

#: Maximum fill→render→measure cycles before failing loudly. The plan's rule is that we
#: never silently truncate, so exhausting this is an error, not a fallback.
MAX_FIT_ATTEMPTS = 3

#: How much to ask the rewriter to shorten by on each successive overflow, in percent.
#: Escalating rather than fixed, because a bullet set that overflows twice needs a bigger
#: cut than the first attempt gave it.
SHORTEN_SCHEDULE = (15, 25, 35)

#: Where `scripts/calibrate.py` writes its measurements, one file per PDF backend.
CALIBRATION_DIR = _dir_from_env("RESUME_TAILOR_CALIBRATION_DIR", DATA_DIR / "calibration")

#: Word-measured values for the current template, used when no calibration file exists.
#: Kept in source so a fresh checkout behaves exactly as it did before calibration became
#: data, and so the Windows path needs no generated file at all.
_FALLBACK_CHARS_PER_LINE = 101
_FALLBACK_LINES_PER_PAGE = 52


def _load_calibration(backend: str) -> tuple[int, int, str]:
    """Read measured fit constants for `backend`, falling back to the Word-derived pair.

    Returns `(chars_per_line, lines_per_page, source)` where `source` names the file used
    or "fallback". The source is reported rather than swallowed because inheriting Word's
    constants under LibreOffice is a silent way to mis-size every page — `report.py` and
    the web UI both surface it.
    """
    path = CALIBRATION_DIR / f"{backend}.json"
    if not path.exists():
        return _FALLBACK_CHARS_PER_LINE, _FALLBACK_LINES_PER_PAGE, "fallback"
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
        return int(raw["chars_per_line"]), int(raw["lines_per_page"]), str(path)
    except (json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            f"{path} is not a usable calibration file ({exc}). Delete it to fall back to "
            f"the built-in constants, or regenerate it with scripts/calibrate.py."
        ) from exc


#: Calibration constants, measured by `scripts/calibrate.py` against the real template and
#: the active PDF backend. Re-run that script after any change to fonts, margins, the
#: template, or the converter — these numbers describe one engine rendering one document.
CHARS_PER_LINE, LINES_PER_PAGE, CALIBRATION_SOURCE = _load_calibration(PDF_BACKEND)

#: Below this fraction of the target page's capacity, a page reads as half-empty and the
#: fit loop restores bullets rather than accepting the result.
#:
#: Raised from 0.85 once widow repair landed. The old value was calibrated against pages
#: that still contained widows, so several of the "full" lines it was counting held a
#: single word. With those gone a measured line is a line of real content.
#:
#: This is the one knob here with a running cost, and it was measured rather than guessed.
#: Same posting, same everything else:
#:
#:   0.92 -> 13 of 15 bullets, 49/52 lines, 3 iterations
#:   0.88 -> 12 of 15 bullets, 47/52 lines, 2 iterations
#:   0.86 -> accepts ~86% fill on first measure; fewer grow rounds when the estimate
#:         undershoots the real render (common after rewrite shortens bullets).
#:
#: One extra rewrite call buys one extra bullet. Lower = fewer API rounds, slightly more
#: whitespace at the bottom; raise toward 0.92 if you want the loop to pack the page tighter.
UNDERFLOW_THRESHOLD = 0.86

# --------------------------------------------------------------------------------------
# Bullet merging (non-regressive, deterministic proposal)
# --------------------------------------------------------------------------------------
#
# Merging combines multiple selected bullet points within a single entry into fewer
# bullets. It is designed as a space lever that must still preserve correctness
# invariants enforced in `rewrite.check_fabrication`.

#: Affinity threshold schedule for merge proposals.
#: Lower thresholds propose more merges as the fit loop escalates on overflow.
MERGE_AFFINITY_SCHEDULE = (0.55, 0.45, 0.35)

#: Weakest-member relevance score gate used by merge proposals.
#:
#: When at least one bullet in a candidate group is weak, merging is allowed even when
#: overall affinity is not yet extremely high. This encodes the "three mediocre
#: bullets become two better ones" idea.
MERGE_WEAK_SCORE = 4.0

#: How much larger the candidate group's source length may be than the merged
#: bullet's hard maximum.
#:
#: The merge output must fit within the same hard `max` constraints used by rewrite.
#: Since the model must compress multiple bullets into one, we only propose merging
#: when the total source text is not more than ~1.8x the hard max. This bounds how
#: much information the merge is allowed to drop.
MERGE_SOURCE_RATIO = 1.8

#: Maximum merge-group size on the first (most conservative) pass.
#:
#: The merge proposal step allows one extra member on later overflow rungs; the
#: feature stays controlled by these caps plus `MAX_MERGES_PER_RUN`.
MAX_MERGE_GROUP_SIZE = 2

#: Maximum number of merge groups the proposal step may select in one fit iteration.
MAX_MERGES_PER_RUN = 3

#: How many times the fit loop may grow the selection to fill an underfull page. Unlike
#: overflow, exhausting this is not an error: a slightly sparse resume is still valid
#: output, so the loop returns the fullest version it reached. The bound exists because
#: each growth costs an API call and a Word render.
MAX_GROW_ATTEMPTS = 4


# --------------------------------------------------------------------------------------
# Line occupancy
# --------------------------------------------------------------------------------------
#
# The character budget is a cliff, not a slope: a bullet two characters past a line
# boundary wraps onto a whole extra line that holds one word. Measured across every render
# in output/, every widowed bullet came back at 204-207 characters against a 202-character
# budget, while the two clean runs had every bullet at 180-199. Two characters per bullet
# was the entire difference.
#
# These live here rather than in fit.py because rewrite.py needs them too, and fit.py
# already imports rewrite — defining them there would invert that dependency.


def line_span(text: str) -> int:
    """How many rendered lines `text` occupies, by the character budget."""
    return max(1, math.ceil(len(text) / CHARS_PER_LINE))


def last_line_fill(text: str) -> int:
    """How many characters land on `text`'s final rendered line.

    A length that is an exact multiple of `CHARS_PER_LINE` fills its last line completely,
    so it returns `CHARS_PER_LINE` rather than 0 — that case is the ideal, not a widow.
    """
    remainder = len(text) % CHARS_PER_LINE
    return remainder or min(len(text), CHARS_PER_LINE)


#: A final line filled below this fraction is a widow. 0.30 (~30 characters) sits clear of
#: both measured populations: real widows filled 2-5 characters of 101, while the tightest
#: legitimate last line observed held 33.
WIDOW_MIN_FILL = 0.30

#: Characters of headroom held back from a line boundary when setting a ceiling. The
#: observed overshoot was 2-5 characters, so a ceiling placed exactly on the boundary would
#: simply be crossed again.
WIDOW_SAFETY = 5


