class Backend(NamedTuple):
    """A fully resolved routing decision for one stage.

    `provider` is the **client shape** `llm.client_for` dispatches on — `anthropic` or
    `openai`, since Ollama/LM Studio/Gemini all speak the same `/chat/completions` shape
    once remapped. `origin` is the **word the user actually typed** (`ollama`, `lmstudio`,
    `gemini`, or `""` for `anthropic`/`openai` specs, which need no disambiguation) — it
    survives the remap so credentials, structured-output policy, and token caps can still
    tell three same-shaped backends apart. Defaulted so existing hand-built `Backend(...)`
    call sites (tests, `report.py`) keep working unchanged.
    """

    provider: str
    model: str
    base_url: str | None
    effort: str
    origin: str = ""

    def label(self) -> str:
        """Human-readable identity, for the run report."""
        return f"{self.origin or self.provider}:{self.model}"


def parse_spec(spec: str) -> tuple[str, str, str | None]:
    """Parse `provider:model[@base_url]` into its parts.

    **Split on the first colon only.** Ollama tags embed colons, so the default model
    `ollama:gemma4:cloud` must yield model `gemma4:cloud`; splitting
    anywhere else breaks the primary use case rather than an edge case.

    A leading segment that is not a known provider means the whole string is a model name
    (`gemma4:cloud` on its own, or `claude-sonnet-5`). The provider is then inferred:
    Anthropic for `claude-*`, Ollama otherwise, since those are the two ways a bare name is
    realistically supplied. Stage overrides under an `lmstudio`/`ollama` profile are
    rebound in `resolve` before this runs so LM Studio ids like `google/gemma-4-12b` do
    not silently become Ollama.
    """
    spec = spec.strip()
    if not spec:
        raise ValueError("Empty model spec.")

    base_url: str | None = None
    if "@" in spec:
        spec, _, base_url = spec.partition("@")
        base_url = base_url or None

    head, sep, tail = spec.partition(":")
    if sep and head.lower() in PROVIDERS:
        provider, model = head.lower(), tail
    else:
        model = spec
        provider = "anthropic" if model.lower().startswith("claude") else "ollama"

    if not model:
        raise ValueError(f"Model spec {spec!r} names a provider but no model.")
    return provider, model, base_url


def _has_explicit_provider(spec: str) -> bool:
    """True when the first `:` segment is a known provider (not part of a model tag)."""
    spec = spec.strip()
    if "@" in spec:
        spec = spec.partition("@")[0]
    head, sep, _tail = spec.partition(":")
    return bool(sep and head.lower() in PROVIDERS)


def _bind_bare_override(override: str, profile_spec: str) -> str:
    """Keep a bare model id on the profile stage's local backend.

    UI overrides are often LM Studio ids (`google/gemma-4-12b`) with no `lmstudio:`
    prefix. Without rebinding, `parse_spec` would infer Ollama and hit :11434. Explicit
    `provider:...` specs and bare `claude-*` names are left alone. When the profile stage
    is Anthropic (e.g. hybrid rewrite), bare non-Claude names still fall through to the
    historical Ollama default.
    """
    override = override.strip()
    if _has_explicit_provider(override) or override.lower().startswith("claude"):
        return override

    provider, _model, base = parse_spec(profile_spec)
    if provider not in ("ollama", "lmstudio", "gemini"):
        return override

    model, o_base = override, None
    if "@" in override:
        model, _, o_base = override.partition("@")
        o_base = o_base or None
    bound = f"{provider}:{model}"
    final_base = o_base or base
    if final_base:
        bound = f"{bound}@{final_base}"
    return bound


def provider_stages(profile: str, provider: str) -> tuple[str, ...]:
    """Which stages of `profile` route to `provider`, so a UI-supplied tag can repoint them.

    Exists because e.g. `OLLAMA_MODEL` is read once at import and baked into
    `MODEL_PROFILES`, which left the web UI able to pick the *profile* but not the *tag* —
    changing model meant editing `.env` and restarting the server. The web layer turns the
    answer here into per-stage `resolve(overrides=...)` entries.

    Returns stages, not a rewritten profile dict, precisely so `hybrid` keeps working:
    its `rewrite` stage is Anthropic and must not be repointed at an Ollama tag. A raw
    spec (not a profile name) is all-or-nothing — every stage already shares it.

    Checks the *pre-remap* provider word (what `parse_spec` returns), not `Backend.origin`
    — this runs before any `Backend` exists.
    """
    specs = MODEL_PROFILES.get(profile.strip())
    if specs is None:
        try:
            spec_provider = parse_spec(profile)[0]
        except ValueError:
            return ()
        return PURPOSES if spec_provider == provider else ()
    return tuple(p for p in PURPOSES if parse_spec(specs[p])[0] == provider)


def ollama_stages(profile: str) -> tuple[str, ...]:
    """`provider_stages(profile, "ollama")` — kept as a thin wrapper for existing callers."""
    return provider_stages(profile, "ollama")


def _backend(spec: str, purpose: str, effort: str | None) -> Backend:
    """Resolve a raw spec into a Backend, remapping local aliases to OpenAI-compat."""
    provider, model, base_url = parse_spec(spec)
    origin = provider
    # All three speak /v1/chat/completions; keep distinct env defaults so switching
    # profiles does not require editing a shared base URL.
    if provider == "ollama":
        provider, base_url = "openai", base_url or OLLAMA_BASE_URL
    elif provider == "lmstudio":
        provider, base_url = "openai", base_url or LMSTUDIO_BASE_URL
    elif provider == "gemini":
        provider, base_url = "openai", base_url or GEMINI_BASE_URL
    return Backend(
        provider=provider,
        model=model,
        base_url=base_url,
        effort=effort or DEFAULT_EFFORT.get(purpose, EFFORT),
        origin=origin,
    )


#: Resolved once per run by `resolve()`. Module state rather than a threaded parameter
#: because it is a process-wide run setting, like OUTPUT_DIR — and threading it would mean
#: touching every function between the CLI and the two API call sites.
_ACTIVE: dict[str, Backend] = {}


def resolve(
    profile: str | None = None,
    *,
    overrides: dict[str, str] | None = None,
    effort: str | None = None,
) -> dict[str, Backend]:
    """Decide which backend serves each stage, for the whole run.

    `profile` is a name from `MODEL_PROFILES` or a raw spec applied to every stage.
    `overrides` routes individual stages (`{"rewrite": "claude-sonnet-5"}`).
    A bare model id in an override keeps the profile stage's ollama/lmstudio backend
    (so `lmstudio` + `google/gemma-4-12b` does not silently call Ollama).

    Called once, early, so a bad spec fails before any file is read or any token spent.
    """
    profile = (profile or "claude").strip()

    if profile in MODEL_PROFILES:
        specs = dict(MODEL_PROFILES[profile])
    elif ":" in profile or "@" in profile or profile.lower().startswith("claude"):
        specs = dict.fromkeys(PURPOSES, profile)
    else:
        raise ValueError(
            f"Unknown model profile {profile!r}. Use one of "
            f"{', '.join(sorted(MODEL_PROFILES))}, or a spec like "
            f"'ollama:{OLLAMA_MODEL}'."
        )

    for purpose, spec in (overrides or {}).items():
        if purpose not in PURPOSES:
            raise ValueError(f"Unknown stage {purpose!r}. Expected one of {PURPOSES}.")
        specs[purpose] = _bind_bare_override(spec, specs[purpose])

    _ACTIVE.clear()
    _ACTIVE.update(
        {p: _backend(specs[p], p, effort) for p in PURPOSES}
    )
    return dict(_ACTIVE)


def backend_for(purpose: str) -> Backend:
    """The resolved backend for one stage, defaulting to Claude if `resolve` never ran.

    The default matters: `jd.extract` and `rewrite.score_table` are importable library
    functions, and tests and scripts call them without going through the CLI.
    """
    if purpose not in PURPOSES:
        raise ValueError(f"Unknown stage {purpose!r}. Expected one of {PURPOSES}.")
    if not _ACTIVE:
        resolve("claude")
    return _ACTIVE[purpose]


def provider_for(purpose: str) -> str:
    return backend_for(purpose).provider


def model_for(purpose: str) -> str:
    return backend_for(purpose).model


def base_url_for(purpose: str) -> str | None:
    return backend_for(purpose).base_url


def effort_for(purpose: str) -> str:
    return backend_for(purpose).effort


def max_token_cap_for(purpose: str) -> int:
    """Ceiling `llm._OpenAICompatClient.request` may escalate a truncated stage up to.

    `LLM_MAX_TOKENS`, if set, pins this (and the starting request — see `max_tokens_for`)
    for every OpenAI-compatible stage, overriding PROVIDER_MAX_TOKENS entirely. Otherwise
    the cap is per-origin: Anthropic's mirrors ANTHROPIC_NONSTREAMING_MAX_TOKENS so the two
    accessors never disagree, Gemini's reflects its real output budget, and every other
    origin (Ollama, LM Studio, plain openai) gets the generic MAX_TOKEN_CAP.
    """
    if _LLM_MAX_TOKENS_ENV is not None:
        return int(_LLM_MAX_TOKENS_ENV)
    origin = backend_for(purpose).origin
    return PROVIDER_MAX_TOKENS.get(origin, MAX_TOKEN_CAP)


def max_tokens_for(purpose: str) -> int:
    """Starting output ceiling for a stage — not necessarily the last one sent.

    Clamped to `max_token_cap_for`, which is what keeps this behaviour-identical to the old
    Anthropic-only clamp: `min(32_000, 21_333)` for Anthropic, `min(32_000, 65_536)` = the
    unclamped 32,000 for everyone else. On the OpenAI-compatible path, a response that
    actually truncates escalates past this up to the same cap — see
    `llm._OpenAICompatClient.request`.
    """
    return min(MAX_TOKENS, max_token_cap_for(purpose))


def structured_mode_for(purpose: str) -> str:
    """How to ask for JSON on the OpenAI-compatible path, for one stage.

    An explicit `LLM_STRUCTURED_MODE` always wins — a user who set it gets it everywhere,
    Gemini included. Left unset, the origin picks: PROVIDER_STRUCTURED_MODE, defaulting to
    the historically-safe "prompt".
    """
    if _STRUCTURED_MODE_ENV is not None:
        return _STRUCTURED_MODE_ENV
    origin = backend_for(purpose).origin
    return PROVIDER_STRUCTURED_MODE.get(origin, "prompt")


#: Env var names `api_key_for` / `credential_gaps` check, in precedence order, keyed by
#: `Backend.origin`. Single source of truth so the two stay in sync. The default arm keeps
#: `lmstudio`/`ollama`/bare-`openai` on the historical `LLM_API_KEY`-then-`OLLAMA_API_KEY`
#: fallback — someone may be proxying LM Studio through a hosted endpoint that wants a key.
_API_KEY_ENV_BY_ORIGIN: dict[str, tuple[str, ...]] = {
    "gemini": ("GEMINI_API_KEY", "GOOGLE_API_KEY", "LLM_API_KEY"),
}
_DEFAULT_API_KEY_ENV = ("LLM_API_KEY", "OLLAMA_API_KEY")


def api_key_env_for(origin: str) -> tuple[str, ...]:
    """Which env vars `api_key_for` checks, in order, for a given `Backend.origin`."""
    return _API_KEY_ENV_BY_ORIGIN.get(origin, _DEFAULT_API_KEY_ENV)


def api_key_for(purpose: str) -> str:
    """Credential for a stage's provider.

    Local and Ollama Cloud endpoints authenticate through the daemon rather than a bearer
    token, so an empty string is a valid answer for most origins — `llm.py` omits the
    header entirely when there is no key, which some servers require. Gemini is the
    exception: `llm.client_for` raises before this is even reached if its key is missing
    (see PROVIDERS_REQUIRING_KEY), so an empty string here would never actually be sent.
    """
    backend = backend_for(purpose)
    if backend.provider == "anthropic":
        return anthropic_api_key()
    for name in api_key_env_for(backend.origin):
        value = os.environ.get(name, "")
        if value:
            return value
    return ""


def credential_gaps(profile: str, overrides: dict[str, str] | None = None) -> list[str]:
    """Which stages of `profile` would fail for lack of a credential, without resolving it.

    Pure: built on `parse_spec` alone, never calls `resolve`, never touches `_ACTIVE`. That
    matters for the web layer — a request-thread validation call that resolved would
    silently reroute a job that is mid-run, since `_ACTIVE` is process-global. An unknown
    profile is not this function's problem (`resolve` raises `ValueError` for that); it
    just reports no gaps.
    """
    if profile.strip() in MODEL_PROFILES:
        specs = dict(MODEL_PROFILES[profile.strip()])
    else:
        try:
            parse_spec(profile)
        except ValueError:
            return []
        specs = dict.fromkeys(PURPOSES, profile)

    for purpose, spec in (overrides or {}).items():
        if purpose in PURPOSES:
            specs[purpose] = _bind_bare_override(spec, specs.get(purpose, spec))

    gaps: list[str] = []
    seen_origins: set[str] = set()
    for spec in specs.values():
        try:
            origin = parse_spec(spec)[0]
        except ValueError:
            continue
        if origin not in PROVIDERS_REQUIRING_KEY or origin in seen_origins:
            continue
        seen_origins.add(origin)
        if not any(os.environ.get(name) for name in api_key_env_for(origin)):
            env_names = " or ".join(api_key_env_for(origin))
            gaps.append(f"{env_names} is not set — required by the {origin!r} provider.")
    return gaps


def fingerprint(purpose: str) -> str:
    """Identity of the backend serving a stage, for cache keys.

    Folded into `jd._slug` and `rewrite._score_cache_path`. Without it, switching models
    and re-running silently serves the *previous* model's output — the same class of bug
    `_PROMPT_VERSION` exists to prevent, and one that would make any A/B between backends
    meaningless. Keyed on `origin or provider`, not `provider` alone: after `_backend`'s
    remap, Ollama, LM Studio, and Gemini all share `provider == "openai"`, so two backends
    with the same model string but different origins would otherwise collide.
    """
    backend = backend_for(purpose)
    return f"{backend.origin or backend.provider}|{backend.model}|{backend.effort}"


# --------------------------------------------------------------------------------------
# PDF rendering backend
# --------------------------------------------------------------------------------------
#
# The fit loop decides overflow on a real page count, which means something has to turn a
# .docx into a PDF. Word via COM does it best and runs only on Windows; LibreOffice
# headless does it anywhere, which is what makes the container possible.
#
# These are not interchangeable to the character: two engines lay text out slightly
# differently, so each carries its own calibration (see below). Switching backend without
# switching constants is the failure this pairing exists to prevent.

PDF_BACKENDS = ("word", "soffice")


def _default_pdf_backend() -> str:
    """Pick a converter for this machine: Word on Windows, LibreOffice elsewhere.

    Overridable with RESUME_TAILOR_PDF_BACKEND, which is how a Windows developer can test
    the container's engine without a container.
    """
    requested = os.environ.get("RESUME_TAILOR_PDF_BACKEND", "auto").strip().lower()
    if requested in PDF_BACKENDS:
        return requested
    if requested not in ("auto", ""):
        raise ValueError(
            f"RESUME_TAILOR_PDF_BACKEND must be one of {PDF_BACKENDS} or 'auto', "
            f"got {requested!r}"
        )
    return "word" if platform.system() == "Windows" else "soffice"


PDF_BACKEND = _default_pdf_backend()

#: How to invoke LibreOffice. The binary is `soffice` on Debian/Ubuntu and macOS; the
#: env var covers installations that are not on PATH.
SOFFICE_BINARY = os.environ.get("SOFFICE_BINARY") or shutil.which("soffice") or "soffice"

#: Seconds allowed for one LibreOffice conversion. A cold start costs a couple of seconds;
