DEFAULT_PAGE_TARGET = 1

#: Maximum fill→render→measure cycles before failing loudly. The plan's rule is that we
#: never silently truncate, so exhausting this is an error, not a fallback.
MAX_FIT_ATTEMPTS = 3

#: How much to ask the rewriter to shorten by on each successive overflow, in percent.
#: Escalating rather than fixed, because a bullet set that overflows twice needs a bigger
#: cut than the first attempt gave it. First step lowered from 15 to 5 so a
#: barely-over-budget draft isn't cut as hard as one that's badly over.
SHORTEN_SCHEDULE = (5, 15, 25)

#: Where `scripts/calibrate.py` writes its measurements, one file per PDF backend.
CALIBRATION_DIR = _dir_from_env("RESUME_TAILOR_CALIBRATION_DIR", DATA_DIR / "calibration")

#: Word-measured values for the current template, used when no calibration file exists.
#: Kept in source so a fresh checkout behaves exactly as it did before calibration became
#: data, and so the Windows path needs no generated file at all.
_FALLBACK_CHARS_PER_LINE = 101
_FALLBACK_LINES_PER_PAGE = 52

#: Plausibility band for a *loaded* calibration file. `calibrate.py` has its own,
#: independent collapsed-search guard that stops a bad measurement from ever being
#: written — this is the second, cheaper line of defense for a file that reached disk
#: anyway (hand-edited, copied from a different template, or written before that guard
#: existed). A `chars_per_line=20` file measured exactly this way once: it silently
#: capped every rewritten bullet at ~15-35 characters for two days before anyone noticed.
PLAUSIBLE_CHARS_PER_LINE = (40, 200)
PLAUSIBLE_LINES_PER_PAGE = (25, 90)


def _load_calibration(backend: str) -> tuple[int, int, str, str | None]:
    """Read measured fit constants for `backend`, falling back to the Word-derived pair.

    Returns `(chars_per_line, lines_per_page, source, rejection)`. `source` names the
    file used, or is literally `"fallback"` when using the built-in constants — checked
    by exact string equality elsewhere (`template_ops.py`, the frontend), so its two
    possible shapes ("fallback" / a path) must never change. `rejection` is `None`
    unless a file existed but its numbers fell outside `PLAUSIBLE_CHARS_PER_LINE`/
    `PLAUSIBLE_LINES_PER_PAGE`, in which case it names what was rejected and why —
    additional detail layered on top of `source == "fallback"`, not a new source shape.
    The source is reported rather than swallowed because inheriting Word's constants
    under LibreOffice is a silent way to mis-size every page — `report.py` and the web
    UI both surface it.
    """
    path = CALIBRATION_DIR / f"{backend}.json"
    if not path.exists():
        return _FALLBACK_CHARS_PER_LINE, _FALLBACK_LINES_PER_PAGE, "fallback", None
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
        chars_per_line = int(raw["chars_per_line"])
        lines_per_page = int(raw["lines_per_page"])
    except (json.JSONDecodeError, KeyError, TypeError, ValueError) as exc:
        raise ValueError(
            f"{path} is not a usable calibration file ({exc}). Delete it to fall back to "
            f"the built-in constants, or regenerate it with scripts/calibrate.py."
        ) from exc

    chars_lo, chars_hi = PLAUSIBLE_CHARS_PER_LINE
    lines_lo, lines_hi = PLAUSIBLE_LINES_PER_PAGE
    if not (chars_lo <= chars_per_line <= chars_hi) or not (lines_lo <= lines_per_page <= lines_hi):
        # A bad file must not brick the app — fall back rather than raise, but name
        # what was rejected so the cause (not just the symptom) is visible wherever
        # CALIBRATION_SOURCE/CALIBRATION_REJECTION are surfaced.
        rejection = (
            f"{path} was rejected: chars_per_line={chars_per_line}, "
            f"lines_per_page={lines_per_page} (plausible ranges are "
            f"{PLAUSIBLE_CHARS_PER_LINE} and {PLAUSIBLE_LINES_PER_PAGE}). Using built-in "
            "constants instead — delete this file and re-run scripts/calibrate.py."
        )
        return _FALLBACK_CHARS_PER_LINE, _FALLBACK_LINES_PER_PAGE, "fallback", rejection
    return chars_per_line, lines_per_page, str(path), None


#: Calibration constants, measured by `scripts/calibrate.py` against the real template and
#: the active PDF backend. Re-run that script after any change to fonts, margins, the
#: template, or the converter — these numbers describe one engine rendering one document.
CHARS_PER_LINE, LINES_PER_PAGE, CALIBRATION_SOURCE, CALIBRATION_REJECTION = _load_calibration(
    PDF_BACKEND
)


def reload_calibration() -> tuple[int, int, str, str | None]:
    """Re-read fit constants from disk into the module-level globals.

    Needed after a web-triggered calibrate so the running process picks up new values
    without a server restart. Returns the same 4-tuple as `_load_calibration`.
    """
    global CHARS_PER_LINE, LINES_PER_PAGE, CALIBRATION_SOURCE, CALIBRATION_REJECTION
    CHARS_PER_LINE, LINES_PER_PAGE, CALIBRATION_SOURCE, CALIBRATION_REJECTION = _load_calibration(
        PDF_BACKEND
    )
    return CHARS_PER_LINE, LINES_PER_PAGE, CALIBRATION_SOURCE, CALIBRATION_REJECTION

#: Below this fraction of the target page's capacity, a page reads as half-empty and the
#: fit loop restores bullets rather than accepting the result.
#:
#: Raised from 0.85 once widow repair landed. The old value was calibrated against pages
#: that still contained widows, so several of the "full" lines it was counting held a
#: single word. With those gone a measured line is a line of real content.
#:
#: This is the one knob here with a running cost, and it was measured rather than guessed.
#: Same posting, same everything else:
#:
#:   0.93 -> grow until ≥93% fill (target density for one-pagers)
#:   0.92 -> 13 of 15 bullets, 49/52 lines, 3 iterations
#:   0.88 -> 12 of 15 bullets, 47/52 lines, 2 iterations
#:   0.86 -> accepts ~86% fill on first measure; fewer grow rounds when the estimate
#:         undershoots the real render (common after rewrite shortens bullets).
#:
#: One extra rewrite call buys one extra bullet. Lower = fewer API rounds, more
#: whitespace; raise toward 0.93 for a denser page (more grow/rewrite rounds).
UNDERFLOW_THRESHOLD = 0.93

#: Extra estimated lines past page capacity that `fit._initial_selection_size` may claim.
#:
#: The first rewrite usually lands under the advertised max, so a small optimism margin
#: packs the opening call denser (e.g. 13/15 instead of 12/15) and avoids a grow round.
#: Raise if first renders are still sparse; lower if overflow/shorten thrashing is common.
INITIAL_SELECTION_OVERSHOOT = 2

#: Fraction of the chosen entries' bullets the *first* selection may claim.
#:
#: 1.0 leaves `fit._initial_selection_size` exactly as it was: the binary search's only
#: bound is what the line estimate says fits (typically 14 of 15). Lowering it caps that
#: search — a ceiling, never a floor, and never below one bullet per entry.
#:
#: This bounds the first draft only. The grow loop still restores toward the full pool
#: when a measured page is under `UNDERFLOW_THRESHOLD`, so on its own a low value mostly
#: trades extra rewrite rounds for the same final page. Lower `UNDERFLOW_THRESHOLD`
#: alongside it to actually end on a sparser page.
#:
#: Distinct from `EXPERIENCE_BULLET_SHARE` (selection scoring block, below): this one
#: bounds the total count; that one has no opinion on the count and instead bounds how it
#: splits between experience and projects.
INITIAL_BULLET_SHARE = 1.0

# --------------------------------------------------------------------------------------
# Bullet merging (non-regressive, deterministic proposal)
# --------------------------------------------------------------------------------------
#
# Merging combines multiple selected bullet points within a single entry into fewer
# bullets. It is designed as a space lever that must still preserve correctness
# invariants enforced in `rewrite.check_fabrication`.

#: Affinity threshold schedule for merge proposals.
#: Lower thresholds propose more merges as the fit loop escalates on overflow.
MERGE_AFFINITY_SCHEDULE = (0.55, 0.45, 0.35)

#: Weakest-member relevance score gate used by merge proposals.
#:
#: When at least one bullet in a candidate group is weak, merging is allowed even when
#: overall affinity is not yet extremely high. This encodes the "three mediocre
#: bullets become two better ones" idea.
MERGE_WEAK_SCORE = 4.0

#: How much larger the candidate group's source length may be than the merged
#: bullet's hard maximum.
#:
#: The merge output must fit within the same hard `max` constraints used by rewrite.
#: Since the model must compress multiple bullets into one, we only propose merging
#: when the total source text is not more than ~1.8x the hard max. This bounds how
#: much information the merge is allowed to drop.
MERGE_SOURCE_RATIO = 1.8

#: Maximum merge-group size on the first (most conservative) pass.
#:
#: The merge proposal step allows one extra member on later overflow rungs; the
#: feature stays controlled by these caps plus `MAX_MERGES_PER_RUN`.
MAX_MERGE_GROUP_SIZE = 2

#: Maximum number of merge groups the proposal step may select in one fit iteration.
MAX_MERGES_PER_RUN = 3

#: How many times the fit loop may grow the selection to fill an underfull page. Unlike
#: overflow, exhausting this is not an error: a slightly sparse resume is still valid
#: output, so the loop returns the fullest version it reached. The bound exists because
#: each growth costs an API call and a Word render.
MAX_GROW_ATTEMPTS = 4


# --------------------------------------------------------------------------------------
# Opening-verb variety
# --------------------------------------------------------------------------------------
#
# A resume whose bullets all open "Designed... Engineered... Architected..." reads as one
# note held too long, and the exact-duplicate case ("Designed" twice) reads as an editing
# mistake. Detecting the second is trivial; detecting the first needs to know that those
# three verbs make the same claim, which is what these families encode.
#
# Membership is deliberately conservative. Only verbs listed here participate in
# family-level collisions, so an opener the table has never seen can never be flagged
# wrongly — the cost of an omission is a missed catch, never a false one.

#: Near-synonymous bullet openers, grouped by the claim they make. Past tense, because
#: that is the register `rewrite._SYSTEM` asks for. Initialised from the built-in
#: `core-tech` pack (`library_seeds.py`) and reassigned wholesale by
#: `libraries.apply_to_config()` once a workspace has its own pack selection — never
#: mutated in place, since `verb_family`'s index cache below keys on object identity.
VERB_FAMILIES: dict[str, tuple[str, ...]] = dict(library_seeds.BUILTIN_PACKS["core-tech"]["verb_families"])

#: How many bullets may open with verbs from the same family before it reads repetitive.
#: Two is the point where a pattern becomes visible but is still plausibly incidental; a
#: third makes the whole resume sound like one sentence.
MAX_SAME_FAMILY_OPENERS = 2


def _build_verb_index(families: dict[str, tuple[str, ...]]) -> dict[str, str]:
    """Invert `families` into {verb: family}, first-wins on a verb listed twice.

    A verb in two families is expected once families come from separately-authored
    packs — "administered" is legitimately both core-tech's `operate` and a nursing
    pack's `care`. Composing packs is `libraries.py`'s job (it resolves the collision by
    pack order and reports it as a diagnostic); this function stays total so a
    hand-edited or partially-composed table can never crash an entrypoint. Duplicate
    detection *within one pack* is a save-time validation rule instead, in
    `libraries.validate_pack`.
    """
    index: dict[str, str] = {}
    for family, verbs in families.items():
        for verb in verbs:
            index.setdefault(verb, family)
    return index


#: Lazily (re)built cache of `_build_verb_index(VERB_FAMILIES)`, invalidated whenever
#: `VERB_FAMILIES` is reassigned to a new object — `libraries.apply_to_config()` and
#: `monkeypatch.setattr(config, "VERB_FAMILIES", ...)` both work this way, so neither
#: needs to know this cache exists. Compared by identity (`is not`), not equality: two
#: equal-but-distinct dicts must still invalidate, since equality on a multi-thousand
#: entry table would cost more than just rebuilding it.
_VERB_INDEX: dict[str, str] | None = None
_VERB_INDEX_SOURCE: object | None = None


def verb_family(word: str) -> str | None:
    """The family `word` belongs to, or None if it is not a known opener.

    Case-insensitive, and tolerant of the trailing punctuation a one-word opener never
    has but a caller might pass in.
    """
    global _VERB_INDEX, _VERB_INDEX_SOURCE
    if _VERB_INDEX is None or _VERB_INDEX_SOURCE is not VERB_FAMILIES:
        _VERB_INDEX = _build_verb_index(VERB_FAMILIES)
        _VERB_INDEX_SOURCE = VERB_FAMILIES
    return _VERB_INDEX.get(word.strip().strip(".,;:").lower())


def family_verbs(family: str) -> tuple[str, ...]:
    """Every known opener in `family`, for suggesting alternatives to the model."""
    return VERB_FAMILIES.get(family, ())


# --------------------------------------------------------------------------------------
# Line occupancy
# --------------------------------------------------------------------------------------
#
# The character budget is a cliff, not a slope: a bullet two characters past a line
# boundary wraps onto a whole extra line that holds one word. Measured across every render
# in output/, every widowed bullet came back at 204-207 characters against a 202-character
# budget, while the two clean runs had every bullet at 180-199. Two characters per bullet
# was the entire difference.
#
# These live here rather than in fit.py because rewrite.py needs them too, and fit.py
# already imports rewrite — defining them there would invert that dependency.


def slugify(label: str) -> str:
    """Lowercase, hyphenated, filesystem/id-friendly form of `label`.

    Shared so `workspace.new_workspace_id` and `data.Experience`'s auto-filled id use the
    same rule — two independent slug functions would drift the moment either one's edge
    cases (accents, leading digits, empty input) were fixed only in one place.
    """
    return re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-")[:40]


def line_span(text: str) -> int:
    """How many rendered lines `text` occupies, by the character budget."""
    return max(1, math.ceil(len(text) / CHARS_PER_LINE))


def last_line_fill(text: str) -> int:
    """How many characters land on `text`'s final rendered line.

    A length that is an exact multiple of `CHARS_PER_LINE` fills its last line completely,
    so it returns `CHARS_PER_LINE` rather than 0 — that case is the ideal, not a widow.
    """
    remainder = len(text) % CHARS_PER_LINE
    return remainder or min(len(text), CHARS_PER_LINE)


def skill_group_line(label: str, items: list[str]) -> str:
    """The text one skills group renders as, for line-budget estimation.

    Shared so `fit._fixed_overhead_lines` and `facets._resolve_skill_group` cannot drift:
    one measures the overhead, the other must not grow it. Mirrors the join in
    `render.build_context`'s skills block. The ": " separator is hardcoded here rather
    than read from `template_profile.SkillsMapping.separator`; if that ever needs
    honouring, this is the one place it lands.
    """
    return f"{label}: {', '.join(items)}"


#: A final line filled below this fraction is a widow. 0.30 (~30 characters) sits clear of
#: both measured populations: real widows filled 2-5 characters of 101, while the tightest
#: legitimate last line observed held 33.
WIDOW_MIN_FILL = 0.30

#: Characters of headroom held back from a line boundary when setting a ceiling. The
#: observed overshoot was 2-5 characters, so a ceiling placed exactly on the boundary would
#: simply be crossed again.
WIDOW_SAFETY = 5


