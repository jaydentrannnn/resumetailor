def active_workspace_id() -> str | None:
    """Id of the workspace the path globals currently point at.

    None means the legacy single-slot layout: no registry has been bootstrapped, so
    every path constant still holds the value it had before workspaces existed.
    """
    return _ACTIVE_WORKSPACE_ID


def workspace_paths(workspace_id: str) -> dict[str, Path]:
    """Every path `set_active_workspace` would bind for `workspace_id`, without binding.

    Exposed separately because create/duplicate/delete need to read or write one
    workspace's directories while a *different* workspace is active.
    """
    data = DATA_ROOT / WORKSPACES_DIRNAME / workspace_id
    templates = TEMPLATES_ROOT / WORKSPACES_DIRNAME / workspace_id
    output = OUTPUT_ROOT / WORKSPACES_DIRNAME / workspace_id
    cache = CACHE_ROOT / WORKSPACES_DIRNAME / workspace_id

    # Calibration is the one path that does not simply follow ROOT/workspaces/<id>: an
    # explicit RESUME_TAILOR_CALIBRATION_DIR override names a root of its own (mirroring
    # DATA_ROOT etc.), while the unset default nests under the workspace's own data dir
    # so the on-disk tree reads well — the alternative, data/calibration/workspaces/<id>,
    # is uglier for no benefit.
    calibration_env = os.environ.get("RESUME_TAILOR_CALIBRATION_DIR")
    calibration = (
        Path(calibration_env).expanduser().resolve() / WORKSPACES_DIRNAME / workspace_id
        if calibration_env
        else data / "calibration"
    )

    return {
        "DATA_DIR": data,
        "TEMPLATES_DIR": templates,
        "OUTPUT_DIR": output,
        "CACHE_DIR": cache,
        "CALIBRATION_DIR": calibration,
        "MASTER_RESUME_PATH": data / "master_resume.json",
        "SETTINGS_PATH": data / "settings.json",
        "DEFAULT_TEMPLATE_PATH": templates / "main_template.docx",
        "BASELINE_TEMPLATE_PATH": templates / "original_export.docx",
        "TEMPLATE_PROFILE_PATH": templates / "template_profile.json",
        "TEMPLATE_LIBRARY_DIR": templates / "library",
    }


def set_active_workspace(workspace_id: str, *, create_dirs: bool = False) -> str:
    """Rebind every path global to `workspace_id`, then reload fit constants.

    Safe across the whole tree for the same reason `reload_calibration` already is:
    there is not one `from config import X` anywhere — every path reference goes
    through `config.X` and resolves on next read. It is NOT safe to call concurrently
    with a running job or a template-tab operation; callers must hold `JobQueue.busy()`
    and `template_ops.LOCK` first — see `workspace.activate`.
    """
    global DATA_DIR, TEMPLATES_DIR, OUTPUT_DIR, CACHE_DIR, CALIBRATION_DIR
    global MASTER_RESUME_PATH, SETTINGS_PATH, DEFAULT_TEMPLATE_PATH
    global BASELINE_TEMPLATE_PATH, TEMPLATE_PROFILE_PATH, TEMPLATE_LIBRARY_DIR
    global _ACTIVE_WORKSPACE_ID

    paths = workspace_paths(workspace_id)
    if create_dirs:
        for key in ("DATA_DIR", "TEMPLATES_DIR", "OUTPUT_DIR", "CACHE_DIR"):
            paths[key].mkdir(parents=True, exist_ok=True)

    DATA_DIR = paths["DATA_DIR"]
    TEMPLATES_DIR = paths["TEMPLATES_DIR"]
    OUTPUT_DIR = paths["OUTPUT_DIR"]
    CACHE_DIR = paths["CACHE_DIR"]
    CALIBRATION_DIR = paths["CALIBRATION_DIR"]
    MASTER_RESUME_PATH = paths["MASTER_RESUME_PATH"]
    SETTINGS_PATH = paths["SETTINGS_PATH"]
    DEFAULT_TEMPLATE_PATH = paths["DEFAULT_TEMPLATE_PATH"]
    BASELINE_TEMPLATE_PATH = paths["BASELINE_TEMPLATE_PATH"]
    TEMPLATE_PROFILE_PATH = paths["TEMPLATE_PROFILE_PATH"]
    TEMPLATE_LIBRARY_DIR = paths["TEMPLATE_LIBRARY_DIR"]
    _ACTIVE_WORKSPACE_ID = workspace_id

    reload_calibration()
    return workspace_id


def anthropic_api_key() -> str:
    """Return the API key, failing with an actionable message if it is missing.

    Read lazily rather than at import time so that offline commands (validating the
    master resume, rendering dummy data) work without a key configured.
    """
    key = os.environ.get("ANTHROPIC_API_KEY")
    if not key:
        raise RuntimeError(
            "ANTHROPIC_API_KEY is not set. Copy .env.example to .env and add your key "
            "(get one at https://console.claude.com/settings/keys)."
        )
    return key


