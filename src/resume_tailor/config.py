#
# Measured: the prompts here are tiny (the largest call sends ~2,800 input tokens and
# returns ~1,250), so at Sonnet rates a run should cost ~$0.03 per call. It bills ~$0.16.
# The difference is reasoning tokens, drawn from MAX_TOKENS and billed as output. Roughly
# 80% of the cost is thinking depth, not the model — which is why EFFORT is a per-stage
# knob below and not a single constant.
#
# `--model` then addresses the other 20% by routing stages at different backends entirely.

#: The seven stages that call a model. Each resolves independently, so the cheap, safe
#: calls (extract, score, facets, skills) can run on a free backend while rewriting — where
#: the fabrication guard lives and where model quality actually shows — stays on Claude.
#: `expand` produces application-form experience descriptions; it follows the profile
#: like the others (Ollama under `ollama`/`hybrid`, Claude under `claude`).
#: `facets` picks project tech tags and coursework for the posting (same risk class as score).
#: `skills` selects/ranks a tailored skills list from a closed pool of the resume's own
#: evidence (same "model selects, code enforces" risk class as facets).
#: `cover` drafts the cover letter's body paragraphs from the *tailored* bullets. It is the
#: only stage that writes free prose, so it carries the widest guard surface (fabrication,
#: numbers, AI tells, word band) — see `coverletter._accept_letter`.
#: `review` is an opt-in hiring-manager pass over already-tailored bullets; suggested
#: rewrites are fabrication-checked and never auto-applied — see `review.review_bullets`.
#: `answer` drafts free-text application-form answers (guarded by `coverletter.check_claims`);
#: the only LLM call inside `resume_tailor.apply`.
