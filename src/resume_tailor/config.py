def workspace_paths(workspace_id: str) -> dict[str, Path]:
    """Every path `set_active_workspace` would bind for `workspace_id`, without binding.

    Exposed separately because create/duplicate/delete need to read or write one
    workspace's directories while a *different* workspace is active.
    """
    data = DATA_ROOT / WORKSPACES_DIRNAME / workspace_id
    templates = TEMPLATES_ROOT / WORKSPACES_DIRNAME / workspace_id
    output = OUTPUT_ROOT / WORKSPACES_DIRNAME / workspace_id
    cache = CACHE_ROOT / WORKSPACES_DIRNAME / workspace_id

    # Calibration is the one path that does not simply follow ROOT/workspaces/<id>: an
    # explicit RESUME_TAILOR_CALIBRATION_DIR override names a root of its own (mirroring
    # DATA_ROOT etc.), while the unset default nests under the workspace's own data dir
    # so the on-disk tree reads well — the alternative, data/calibration/workspaces/<id>,
    # is uglier for no benefit.
    calibration_env = os.environ.get("RESUME_TAILOR_CALIBRATION_DIR")
    calibration = (
        Path(calibration_env).expanduser().resolve() / WORKSPACES_DIRNAME / workspace_id
        if calibration_env
        else data / "calibration"
    )

    return {
        "DATA_DIR": data,
        "TEMPLATES_DIR": templates,
        "OUTPUT_DIR": output,
        "CACHE_DIR": cache,
        "CALIBRATION_DIR": calibration,
        "MASTER_RESUME_PATH": data / "master_resume.json",
        "SETTINGS_PATH": data / "settings.json",
        "SOURCE_STATUS_PATH": data / "source_status.json",
        "LIBRARIES_PATH": data / "libraries.json",
        "APPLICATIONS_PATH": data / "applications.json",
        "APPLICANT_PROFILE_PATH": data / "applicant_profile.json",
        "APPLICATIONS_OUTPUT_DIR": output / "applications",
        "DEFAULT_TEMPLATE_PATH": templates / "main_template.docx",
        "BASELINE_TEMPLATE_PATH": templates / "original_export.docx",
        "TEMPLATE_PROFILE_PATH": templates / "template_profile.json",
        "TEMPLATE_LIBRARY_DIR": templates / "library",
        "COVER_TEMPLATE_PATH": templates / "cover_template.docx",
        "COVER_TEMPLATE_META_PATH": templates / "cover_template.meta.json",
    }


