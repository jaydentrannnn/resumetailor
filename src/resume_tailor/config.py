#: Weight applied to a bullet matching a JD "must have" keyword vs a "nice to have".
MUST_HAVE_WEIGHT = 3.0
NICE_TO_HAVE_WEIGHT = 1.0

#: Weight for a *soft-skill* must-have ("communication", "teamwork", "leadership") in place
#: of MUST_HAVE_WEIGHT. Lower deliberately: soft tags are broad and sit on almost every
#: entry, including the volunteer and support roles, so at full weight a posting naming
#: three of them as required could float a non-technical entry over a relevant job. Measured
#: on a data-operations posting: once soft skills actually matched tags, an office-assistant
#: entry went from 0.0 to 7.0 while the current internship sat at 12.5.
#:
#: Only `must_have` is split this way. `nice_to_have` stays at NICE_TO_HAVE_WEIGHT for both
#: kinds — at 1.0 the distortion never showed up, and a second knob with no failure behind
#: it is one more thing to keep calibrated.
SOFT_SKILL_WEIGHT = 1.5

#: Multiplier on the LLM relevance score (0-10 per bullet) from `rewrite.score_table`, which
#: is *added* to the keyword score rather than replacing it. The two signals answer different
#: questions: tag overlap asks "did they literally use this tool", the semantic score asks
#: "is this bullet relevant to this role at all" — the latter is the only one that can see
#: domain resonance a tag cannot encode (an academic-advising project against a posting about
#: academic content partnerships).
#:
#: At 0.5 a perfect 10/10 contributes 5.0, comparable to a technical must-have, so neither
#: signal can silently dominate. **At 0.0 scoring is byte-identical to keyword-only**, which
#: is what makes the semantic layer A/B-testable: run the same posting at 0.0 and 0.5 and
#: diff the report rather than guessing which change moved the ranking.
SEMANTIC_WEIGHT = 0.5

#: Small nudge toward bullets carrying a concrete metric, which read stronger at equal
#: keyword relevance.
METRIC_BONUS = 0.5

#: How many entries each section may show. Experience and projects are ranked separately
#: against these caps, so a job only ever competes with other jobs — pooling them let side
#: projects push out the current employer.
#:
#: These are a shape decision, not a fitting one: the fit loop trims *bullets* within the
#: chosen entries and never drops an entry to save space.
MAX_EXPERIENCE_ENTRIES = 3
MAX_PROJECT_ENTRIES = 2

