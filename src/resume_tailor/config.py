MODEL = "claude-sonnet-5"

#: Generous *starting* request — these are non-streaming calls whose real output is a few
#: KB of JSON, so this exists to prevent truncation, not to bound cost. It is no longer the
#: last word: `llm._OpenAICompatClient.request` escalates past it on the OpenAI-compatible
#: path when a response actually truncates (`finish == "length"`), up to `max_token_cap_for`.
#: A fixed ceiling stopped being enough once Gemini entered the mix — it counts thinking
#: tokens against `maxOutputTokens`, so a verbose stage could truncate outright with no
#: recovery. `MAX_TOKENS` still matters: it is what every *working* call is billed at, and
#: escalation only fires on what would otherwise be a hard failure (see `max_token_cap_for`).
#:
#: This is the *requested* ceiling, not necessarily the one sent. Anthropic refuses a
#: non-streaming request above 21,333 outright, so `max_tokens_for()` clamps that path —
#: read it before assuming a Claude run actually gets this budget. The Anthropic path never
#: escalates (see PROVIDER_MAX_TOKENS) — raising it means streaming, not this constant.
MAX_TOKENS = 32_000

#: Anthropic's hard limit for a non-streaming request: the SDK rejects anything where
#: `3600 * max_tokens / 128_000 > 600` with "Streaming is required...". It is a client-side
#: refusal, so an over-large value fails before a token is spent rather than degrading.
#: Lifting it means converting the call sites to streaming, not raising this number.
ANTHROPIC_NONSTREAMING_MAX_TOKENS = 21_333

#: Ceiling `max_tokens_for` will escalate an OpenAI-compatible stage up to, for a provider
#: with no entry in PROVIDER_MAX_TOKENS below. Ollama/LM Studio ids vary too much by model
#: to hardcode; this is a generous default that lets escalation help without guessing wrong.
MAX_TOKEN_CAP = 65_536

#: Per-origin override of MAX_TOKEN_CAP, keyed by `Backend.origin` (the word the user typed,
#: not the client shape `_backend` remaps to). Anthropic's entry mirrors
#: ANTHROPIC_NONSTREAMING_MAX_TOKENS so `max_token_cap_for` and `max_tokens_for` agree
#: without a separate anthropic-specific branch. Gemini 2.5+ output budgets run to 65,536.
PROVIDER_MAX_TOKENS: dict[str, int] = {
    "anthropic": ANTHROPIC_NONSTREAMING_MAX_TOKENS,
    "gemini": 65_536,
}

#: Escalation attempts `llm._OpenAICompatClient.request` makes on a truncated response
#: before giving up — bounded independently of the cap itself (a huge LLM_MAX_TOKENS
#: override should not turn one truncation into an unbounded doubling loop).
MAX_TOKEN_ESCALATIONS = 2

#: Pins BOTH the starting request and the escalation cap for every OpenAI-compatible stage,
#: overriding PROVIDER_MAX_TOKENS entirely. This is the "stop adapting, I already know the
#: right number" escape hatch — unset (the default) leaves the ceiling adaptive.
_LLM_MAX_TOKENS_ENV = os.environ.get("LLM_MAX_TOKENS")

#: Thinking depth. JD extraction and bullet rewriting are short, well-specified tasks;
#: "medium" is the cost/quality sweet spot and can be raised if rewrites come back bland.
#: Passed as `output_config={"effort": ...}` by both API calls — see MAX_TOKENS above.
#:
#: This is now only the *fallback* default; per-stage effort is resolved through
#: `effort_for()` below, because effort is where most of the bill actually goes.
EFFORT = "medium"


